// Static description of the litePlay API
//
// Shape of an entry:
//   name       canonical name (the idiomatic one, e.g. "piano")
//   kind       function | class | method | namespace | instrument | constant | family
//   receiver   null for globals, otherwise the namespace/class that owns it
//   category   coarse grouping used for ranking and UI sections
//   signature  display form, null when the name is not callable
//   params     [{ name, type, default?, range?, optional?, rest? }]
//   returns    display type, null when nothing useful is returned
//   alias      { en: [...], pt: [...] } alternate spellings
//   summary    one line, shown in completion info
//   example    working litePlay code
//   program    instrument only: GM program number
//   isDrums    instrument only
//   value      constant only
//   pattern    family only: RegExp matching every name in the family

const alias = (en = [], pt = []) => ({ en, pt });

const DEFAULTS = {
  kind: "function",
  receiver: null,
  category: "misc",
  signature: null,
  params: [],
  returns: null,
  alias: alias(),
  summary: "",
  example: null,
};

const entry = (fields) => ({ ...DEFAULTS, ...fields });

